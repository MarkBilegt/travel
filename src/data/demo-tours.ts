type Day = [it: string, itText: string, en: string, enText: string, overnight?: AccommodationKey, region?: string]
const days = (list: Day[], from = 1) =>
  list.map(([title, description, , , overnight, region], i): ItineraryDay => ({ day: from + i, title, description, overnight, region }))
const daysEn = (list: Day[], numbers?: number[]) =>
  list.map(([, , title, description, overnight, region], i): ItineraryDay => ({ day: numbers?.[i] ?? i + 1, title, description, overnight, region }))
/** Days that are grouped keep their real day number (e.g. a three-day trek is one entry starting at day 10). */
const numbered = (list: Day[], numbers: number[]) => days(list).map((d, i) => ({ ...d, day: numbers[i] }))

